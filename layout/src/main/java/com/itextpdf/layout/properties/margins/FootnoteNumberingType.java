package com.itextpdf.layout.properties.margins;

/**
 * Enum representing possible values for footnote anchors (and numbering)
 * specified via {@link FootnotesProperties#setFootnoteNumberingType(FootnoteNumberingType)}.
 */
public enum FootnoteNumberingType {
    DECIMAL,
    ROMAN_LOWER,
    ROMAN_UPPER,
    ENGLISH_LOWER,
    ENGLISH_UPPER,
    GREEK_LOWER,
    GREEK_UPPER
}
